"""Wrap the extracted model (extract.py output) as the editor's seed script.

Usage: python3 -I build_seed.py <model.json> <out.js>
"""
import json, sys

model = json.load(open(sys.argv[1]))

# OEM wire colours, as drawn on MF0015-54, and the Mad Folk harness colour each maps to
colors = [
    dict(code='BK', name='Black', hex='#545454', mf='BK'),
    dict(code='DBR', name='Dark brown', hex='#b8735c', mf='BR'),
    dict(code='DBL', name='Dark blue', hex='#003fff', mf='BL/BK'),
    dict(code='DGN', name='Dark green', hex='#00b85c', mf='GN/BK'),
    dict(code='GY', name='Grey', hex='#989898', mf='GY'),
    dict(code='LBL', name='Light blue', hex='#7fdfff', mf='BL'),
    dict(code='LGN', name='Light green', hex='#7fff7f', mf='GN'),
    dict(code='OR', name='Orange', hex='#ff7f00', mf='OR'),
    dict(code='PK', name='Pink', hex='#ff7fdf', mf='PK'),
    dict(code='PU', name='Purple', hex='#a500dd', mf='VT'),
    dict(code='R', name='Red', hex='#ff0000', mf='R'),
    dict(code='LBR', name='Light brown', hex='#dda56e', mf='BR'),
    dict(code='W', name='White', hex='#fafafa', mf='W', outline=True),
    dict(code='Y', name='Yellow', hex='#f4d715', mf='Y'),
    dict(code='WOP', name='White - orange/purple trace', hex='#fafafa', outline=True, tracer='#ff7f00', tracer2='#a500dd', mf='OR'),
]
mf_colors = [
    dict(code='BK', name='Black', hex='#545454'),
    dict(code='BR', name='Brown', hex='#b8735c'),
    dict(code='BL/BK', name='Blue / black trace', hex='#7fdfff', tracer='#222222'),
    dict(code='GN/BK', name='Green / black trace', hex='#7fff7f', tracer='#222222'),
    dict(code='GY', name='Grey', hex='#989898'),
    dict(code='BL', name='Blue', hex='#7fdfff'),
    dict(code='GN', name='Green', hex='#7fff7f'),
    dict(code='OR', name='Orange', hex='#ff7f00'),
    dict(code='PK', name='Pink', hex='#ff00ff'),
    dict(code='VT', name='Violet', hex='#d19cc7'),
    dict(code='R', name='Red', hex='#ff0000'),
    dict(code='W', name='White', hex='#fafafa', outline=True),
    dict(code='Y', name='Yellow', hex='#f4d715'),
]

components = []
for c in model['components']:
    o = dict(c)
    if c['type'] not in ('splice', 'terminal'):
        o['style'] = 'art'
    else:
        o['style'] = c['type']
        o.pop('art', None)
    if c['type'] == 'panel':
        o['locked'] = c['id'] == 'SHEET'
    if '(optional)' in c['name']:
        o['optional'] = True
    if c['type'] == 'splice':
        o['name'] = c['id'].replace('SP', 'Splice ')
    components.append(o)

wires = []
for w in model['wires']:
    o = dict(id=w['id'], circuit=w['circuit'], color=w['color'], gauge='', length='', notes='',
             from_=w['frm'], to=w['to'], points=w['points'], labels=w['labels'])
    if w['circuit'] == '15003':
        o['gauge'] = '14 AWG'
        o['notes'] = ('Originally a resistive wire - replaced with a 14 AWG wire. If using points '
                      'ignition a ballast resistor of 1.6 Ohm should be used at the coil.')
    o['from'] = o.pop('from_')
    wires.append(o)

doc = dict(
    version=1,
    meta=dict(
        title='EH Holden with Mad Folk circuit numbers',
        description='EH Holden with Mad Folk circuit numbers, alternator (built in reg), headlight relay upgrade',
        drawingNo='MF0015-54', drawnBy='RN', created='2022-01-21',
        source='Mad Folk Engineering drawing MF0015-54 (sheet 1 of 1)',
    ),
    page=dict(w=1190.55, h=841.89),
    reference=dict(href='assets/eh-reference.png', x=0, y=0, w=1190.55, h=841.89),
    colors=colors,
    mfColors=mf_colors,
    components=components,
    wires=wires,
)
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/build_seed.py from the MF0015-54 SVG export. Do not edit by hand.\n')
    f.write('window.HARNESS_SEEDS = window.HARNESS_SEEDS || {};\n')
    f.write('window.HARNESS_SEEDS["eh-holden"] = ')
    json.dump(doc, f, separators=(',', ':'))
    f.write(';\n')
